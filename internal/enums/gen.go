//go:build ignore

// gen writes enums_gen.go from the Engine spec, so validators cannot drift.
// Run it with: go generate ./internal/enums
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"

	"gopkg.in/yaml.v3"
)

const specPath = "../apicontract/engine.yaml"

// OpenAPI schema name -> exported Go identifier, in output order.
var enums = [][2]string{
	{"IntegrationsEnum", "Integrations"},
	{"IntegrationJobsEnum", "IntegrationJobs"},
	{"SensorChecksEnum", "SensorChecks"},
	{"AlertLevelTypes", "AlertLevels"},
	{"NotificationTypesEnum", "NotificationTypes"},
	{"OperationType", "OperationTypes"},
	{"PipelineRunStatus", "PipelineRunStatuses"},
	{"StorageProvider", "StorageProviders"},
	{"AssetTypeEnum", "AssetTypes"},
	{"AssetStatus", "AssetStatuses"},
	{"IntegrationStatusEnum", "IntegrationStatuses"},
	{"AuthStatus", "AuthStatuses"},
	{"MonitorGroupByEnum", "MonitorGroupBys"},
	{"IncidentSeverityEnum", "IncidentSeverities"},
	{"AlertBudgetRefillCadenceEnum", "AlertBudgetRefillCadences"},
	{"CredentialStoresEnum", "CredentialStores"},
	{"ConcurrencyOnLimit", "ConcurrencyOnLimits"},
}

func main() {
	raw, err := os.ReadFile(specPath)
	if err != nil {
		log.Fatal(err)
	}
	var spec struct {
		Components struct {
			Schemas map[string]struct {
				Enum []string `yaml:"enum"`
			} `yaml:"schemas"`
		} `yaml:"components"`
	}
	if err := yaml.Unmarshal(raw, &spec); err != nil {
		log.Fatalf("parse %s: %v", specPath, err)
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by gen.go. DO NOT EDIT.\n\n")
	b.WriteString("// Package enums holds the string enumerations declared in the Orchestra\n")
	b.WriteString("// OpenAPI spec, for use in Terraform schema validators.\n")
	b.WriteString("package enums\n\n")
	b.WriteString("//go:generate go run gen.go\n\n")

	for _, e := range enums {
		schema, goName := e[0], e[1]
		values := spec.Components.Schemas[schema].Enum
		if len(values) == 0 {
			log.Fatalf("schema %s is missing from %s or has no enum values", schema, specPath)
		}
		fmt.Fprintf(&b, "// %s is components.schemas.%s.\nvar %s = []string{\n", goName, schema, goName)
		for _, v := range values {
			fmt.Fprintf(&b, "\t%q,\n", v)
		}
		b.WriteString("}\n\n")
	}

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("enums_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
