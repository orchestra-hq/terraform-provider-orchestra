#!/usr/bin/env python3

"""
Generate Go slices of the OpenAPI string enums used by provider validators.

The `integration` validator on the assets data source had drifted 13 values
behind the spec; generating the lists removes that whole class of bug.

Usage:
    python3 scripts/generate_enums.py --openapi openapi.yaml \
        --out internal/enums/enums_gen.go
"""

from __future__ import annotations

import argparse

# OpenAPI schema name -> exported Go identifier.
ENUMS: dict[str, str] = {
    "IntegrationsEnum": "Integrations",
    "IntegrationJobsEnum": "IntegrationJobs",
    "SensorChecksEnum": "SensorChecks",
    "AlertLevelTypes": "AlertLevels",
    "NotificationTypesEnum": "NotificationTypes",
    "OperationType": "OperationTypes",
    "PipelineRunStatus": "PipelineRunStatuses",
    "StorageProvider": "StorageProviders",
    "AssetTypeEnum": "AssetTypes",
    "AssetStatus": "AssetStatuses",
    "IntegrationStatusEnum": "IntegrationStatuses",
    "AuthStatus": "AuthStatuses",
    "MonitorGroupByEnum": "MonitorGroupBys",
    "IncidentSeverityEnum": "IncidentSeverities",
    "AlertBudgetRefillCadenceEnum": "AlertBudgetRefillCadences",
    "CredentialStoresEnum": "CredentialStores",
}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--openapi", default="openapi.yaml")
    parser.add_argument("--out", default="internal/enums/enums_gen.go")
    args = parser.parse_args()

    try:
        import yaml  # type: ignore
    except Exception as e:
        raise SystemExit("Missing dependency 'pyyaml'. Install with: pip install pyyaml") from e

    with open(args.openapi, "r", encoding="utf-8") as f:
        spec = yaml.safe_load(f)

    schemas = (spec.get("components") or {}).get("schemas") or {}

    lines: list[str] = [
        "// Code generated by scripts/generate_enums.py. DO NOT EDIT.",
        "",
        "// Package enums holds the string enumerations declared in the Orchestra",
        "// OpenAPI spec, for use in Terraform schema validators.",
        "package enums",
        "",
    ]

    for schema_name, go_name in ENUMS.items():
        schema = schemas.get(schema_name)
        if schema is None:
            raise SystemExit(f"Schema {schema_name!r} not found in {args.openapi}")
        values = schema.get("enum")
        if not values:
            raise SystemExit(f"Schema {schema_name!r} has no enum values")

        lines.append(f"// {go_name} is components.schemas.{schema_name}.")
        lines.append(f"var {go_name} = []string{{")
        for value in values:
            lines.append(f'\t"{value}",')
        lines.append("}")
        lines.append("")

    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
